export function getCompetitionPoints(
  category: TournamentCategory,
  confirmedPairCount: number,
  rank: number
): number | undefined {
  const scale = POINT_SCALES[category];
  if (
    !scale ||
    !Number.isInteger(confirmedPairCount) ||
    !Number.isInteger(rank) ||
    confirmedPairCount < scale.firstTeamCount ||
    rank < 1 ||
    rank > confirmedPairCount
  ) {
    return undefined;
  }

  const bandIndex = scale.bands.findIndex(maxTeams => confirmedPairCount <= maxTeams);
  const values = scale.rows[rank - 1]?.split(/\s+/).map(Number) ?? [];
  const firstBandIndex = Math.max(
    0,
    Math.floor((rank - 1) / 4) - (scale.firstRankBandOffset ?? 1)
  );
  const value = values[bandIndex - firstBandIndex];
  return Number.isFinite(value) ? value : undefined;
}
